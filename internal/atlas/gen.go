//go:build ignore

// gen.go makes web/skydata.js, the stars and constellations of the sky map
// of the atlas, from d3-celestial (https://github.com/ofrohn/d3-celestial,
// © Olaf Frohn, BSD 3-Clause): the stars to magnitude 6 with their colour
// index, the Russian names of the bright ones, the lines and the Russian
// names of the constellations, the Milky Way as a grid of its brightness;
// and web/skystars8.js, the fainter stars to magnitude 8, loaded by the map
// when it is zoomed in.
//
// Run it with `go generate ./internal/atlas`.
package main

import (
	"bytes"
	"encoding/base64"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"io"
	"log"
	"math"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const base = "https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/"

func get(u string) []byte {
	resp, err := http.Get(u)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", u, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}

func fetch(name string, v any) {
	resp, err := http.Get(base + name)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", name, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(b, v); err != nil {
		log.Fatalf("%s: %v", name, err)
	}
}

// ra: d3-celestial keeps it from −180 to 180
func ra(v float64) float64 { return math.Mod(v+360, 360) }

func r2(v float64) string { return strconv.FormatFloat(math.Round(v*100)/100, 'f', -1, 64) }

type starList struct {
	Features []struct {
		ID         any `json:"id"`
		Properties struct {
			Mag float64 `json:"mag"`
			BV  string  `json:"bv"`
		} `json:"properties"`
		Geometry struct {
			Coordinates []float64 `json:"coordinates"`
		} `json:"geometry"`
	} `json:"features"`
}

// header: what the files are made of, with the licence of the data
func header(b *bytes.Buffer) {
	b.WriteString("// Generated by gen.go from d3-celestial (github.com/ofrohn/d3-celestial). Do not edit.\n//\n")
	for _, l := range strings.Split(strings.TrimSpace(string(get("https://raw.githubusercontent.com/ofrohn/d3-celestial/master/LICENSE"))), "\n") {
		b.WriteString(strings.TrimRight("// "+l, " ") + "\n")
	}
	b.WriteString("//\n")
}

// milkyWay: the brightness of the Milky Way by degree (dec from −90 up, ra
// from 0 east), the number of its outlines (0…5) around the point, as a
// string of digits
func milkyWay() string {
	var mw struct {
		Features []struct {
			Geometry struct {
				Coordinates [][][][]float64 `json:"coordinates"`
			} `json:"geometry"`
		} `json:"features"`
	}
	fetch("mw.json", &mw)
	// a point is inside when a ray from it to the north pole crosses the
	// outlines an odd number of times: the outlines going round the whole
	// sky need no closing then; the edges go the short way in ra
	grid := make([]byte, 360*180)
	for _, f := range mw.Features {
		var edges [][4]float64 // ra1, dec1, Δra, dec2
		for _, poly := range f.Geometry.Coordinates {
			for _, r := range poly {
				for k := range r {
					p, q := r[k], r[(k+1)%len(r)]
					d := math.Mod(ra(q[0])-ra(p[0])+540, 360) - 180
					if d != 0 {
						edges = append(edges, [4]float64{ra(p[0]), p[1], d, q[1]})
					}
				}
			}
		}
		for x := 0; x < 360; x++ {
			a := float64(x) + 0.5 + 1.234e-6 // off the vertices: the data has points on half degrees
			var cross []float64              // the dec where edges cross this meridian
			for _, e := range edges {
				var t float64
				if e[2] > 0 {
					t = math.Mod(a-e[0]+360, 360)
					if t >= e[2] {
						continue
					}
				} else {
					t = math.Mod(e[0]-a+360, 360)
					if t == 0 || t > -e[2] {
						continue
					}
				}
				cross = append(cross, e[1]+(e[3]-e[1])*t/math.Abs(e[2]))
			}
			for y := 0; y < 180; y++ {
				dec, n := float64(y)-89.5, 0
				for _, c := range cross {
					if c > dec {
						n++
					}
				}
				if n%2 == 1 {
					grid[y*360+x]++
				}
			}
		}
	}
	for i := range grid {
		grid[i] += '0'
	}
	return string(grid)
}

func main() {
	var stars starList
	fetch("stars.6.json", &stars)
	var names map[string]struct {
		RU    string `json:"ru"`
		Bayer string `json:"bayer"`
		C     string `json:"c"`
	}
	fetch("starnames.json", &names)
	var lines struct {
		Features []struct {
			Geometry struct {
				Coordinates [][][]float64 `json:"coordinates"`
			} `json:"geometry"`
		} `json:"features"`
	}
	fetch("constellations.lines.json", &lines)
	var cons struct {
		Features []struct {
			Properties struct {
				RU   string `json:"ru"`
				Rank string `json:"rank"`
			} `json:"properties"`
			Geometry struct {
				Coordinates []float64 `json:"coordinates"`
			} `json:"geometry"`
		} `json:"features"`
	}
	fetch("constellations.json", &cons)

	sort.SliceStable(stars.Features, func(i, j int) bool { return stars.Features[i].Properties.Mag < stars.Features[j].Properties.Mag })
	var b bytes.Buffer
	header(&b)
	b.WriteString("// stars: ra, dec (J2000, degrees), magnitude, colour index B−V, the brightest first; names: index → name;\n")
	b.WriteString("// lines: the figures of the constellations, ra, dec pairs; cons: name, ra, dec, rank;\n")
	b.WriteString("// mw: the Milky Way, 0…5 by degree, rows of ra 0…359 from dec −90 up.\n")
	b.WriteString("window.SkyData = {\nstars: [")
	starNames := map[int]string{}
	for i, f := range stars.Features {
		c := f.Geometry.Coordinates
		bv, err := strconv.ParseFloat(f.Properties.BV, 64)
		if err != nil {
			bv = 0.6
		}
		if i > 0 {
			b.WriteByte(',')
		}
		fmt.Fprintf(&b, "%s,%s,%s,%s", r2(ra(c[0])), r2(c[1]), r2(f.Properties.Mag), r2(bv))
		if n, ok := names[fmt.Sprint(f.ID)]; ok && n.RU != "" && f.Properties.Mag <= 3 {
			starNames[i] = n.RU
		}
	}
	b.WriteString("],\nnames: {")
	keys := make([]int, 0, len(starNames))
	for k := range starNames {
		keys = append(keys, k)
	}
	sort.Ints(keys)
	for i, k := range keys {
		if i > 0 {
			b.WriteByte(',')
		}
		n, _ := json.Marshal(starNames[k])
		fmt.Fprintf(&b, "%d:%s", k, n)
	}
	b.WriteString("},\nlines: [")
	first := true
	for _, f := range lines.Features {
		for _, l := range f.Geometry.Coordinates {
			if !first {
				b.WriteByte(',')
			}
			first = false
			b.WriteByte('[')
			for k, p := range l {
				if k > 0 {
					b.WriteByte(',')
				}
				fmt.Fprintf(&b, "%s,%s", r2(ra(p[0])), r2(p[1]))
			}
			b.WriteByte(']')
		}
	}
	b.WriteString("],\ncons: [")
	for i, f := range cons.Features {
		if i > 0 {
			b.WriteByte(',')
		}
		n, _ := json.Marshal(f.Properties.RU)
		rank, _ := strconv.Atoi(f.Properties.Rank)
		c := f.Geometry.Coordinates
		fmt.Fprintf(&b, "[%s,%s,%s,%d]", n, r2(ra(c[0])), r2(c[1]), rank)
	}
	b.WriteString("],\nmw: \"" + milkyWay() + "\"\n};\n")
	if err := os.WriteFile("web/skydata.js", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("звёзд %d, с именами %d, линий %d, созвездий %d, %d КБ", len(stars.Features), len(starNames), len(lines.Features), len(cons.Features), b.Len()/1024)

	// the fainter stars, six bytes each: ra by 360/65536°, dec by 90/32767°
	// (little endian), (magnitude + 2) × 20, B−V × 50
	have := map[string]bool{}
	for _, f := range stars.Features {
		have[fmt.Sprint(f.ID)] = true
	}
	var faint starList
	fetch("stars.8.json", &faint)
	sort.SliceStable(faint.Features, func(i, j int) bool { return faint.Features[i].Properties.Mag < faint.Features[j].Properties.Mag })
	var bin []byte
	n := 0
	for _, f := range faint.Features {
		if have[fmt.Sprint(f.ID)] {
			continue
		}
		c := f.Geometry.Coordinates
		bv, err := strconv.ParseFloat(f.Properties.BV, 64)
		if err != nil {
			bv = 0.6
		}
		bin = binary.LittleEndian.AppendUint16(bin, uint16(int(math.Round(ra(c[0])/360*65536))%65536))
		bin = binary.LittleEndian.AppendUint16(bin, uint16(int16(math.Round(c[1]/90*32767))))
		bin = append(bin, byte(math.Round(math.Min(math.Max((f.Properties.Mag+2)*20, 0), 255))), byte(int8(math.Round(math.Min(math.Max(bv*50, -128), 127)))))
		n++
	}
	var b8 bytes.Buffer
	header(&b8)
	b8.WriteString("// The stars fainter than in skydata.js, to magnitude 8, six bytes each in base64: ra × 65536/360 (uint16),\n")
	b8.WriteString("// dec × 32767/90 (int16), (magnitude + 2) × 20 (uint8), B−V × 50 (int8); the brightest first.\n")
	b8.WriteString("window.SkyStars8 = \"" + base64.StdEncoding.EncodeToString(bin) + "\";\n")
	if err := os.WriteFile("web/skystars8.js", b8.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("слабых звёзд %d, %d КБ", n, b8.Len()/1024)
}
